  // Opcjonalna obsługa wgranego pliku TrueType (.ttf) z FontStruct (IndexedDB)
  const FONT_DB = 'legendariada_font_db';
  const FONT_STORE = 'fonts';
  let customFontFamily = null;
  let customFontName = null;

  function openFontDb() {
    if (typeof indexedDB === 'undefined') return Promise.resolve(null);
    return new Promise(function (resolve) {
      try {
        const req = indexedDB.open(FONT_DB, 1);
        req.onupgradeneeded = function () {
          if (!req.result.objectStoreNames.contains(FONT_STORE)) {
            req.result.createObjectStore(FONT_STORE, { keyPath: 'id' });
          }
        };
        req.onsuccess = function () { resolve(req.result); };
        req.onerror = function () { resolve(null); };
      } catch (e) {
        resolve(null);
      }
    });
  }

  async function loadFontFaceFromBuffer(name, buffer) {
    if (typeof FontFace === 'undefined' || !document.fonts) return false;
    const face = new FontFace('FamiliadaCustomTTF', buffer);
    await face.load();
    document.fonts.add(face);
    customFontFamily = 'FamiliadaCustomTTF';
    customFontName = name || 'familiada.ttf';
    return true;
  }

  async function initCustomFont() {
    const db = await openFontDb();
    if (db) {
      try {
        const row = await new Promise(function (resolve) {
          const tx = db.transaction(FONT_STORE, 'readonly');
          const req = tx.objectStore(FONT_STORE).get('primary');
          req.onsuccess = function () { resolve(req.result || null); };
          req.onerror = function () { resolve(null); };
        });
        if (row && row.data) {
          await loadFontFaceFromBuffer(row.name, row.data);
          return true;
        }
      } catch (e) {
        // Ignoruj błąd odczytu czcionki
      }
    }
    return false;
  }

  async function setCustomFontFile(file) {
    const buffer = await file.arrayBuffer();
    await loadFontFaceFromBuffer(file.name, buffer);
    const db = await openFontDb();
    if (db) {
      await new Promise(function (resolve) {
        const tx = db.transaction(FONT_STORE, 'readwrite');
        tx.objectStore(FONT_STORE).put({ id: 'primary', name: file.name, data: buffer });
        tx.oncomplete = resolve;
        tx.onerror = resolve;
      });
    }
    return file.name;
  }

  async function clearCustomFont() {
    customFontFamily = null;
    customFontName = null;
    const db = await openFontDb();
    if (db) {
      await new Promise(function (resolve) {
        const tx = db.transaction(FONT_STORE, 'readwrite');
        tx.objectStore(FONT_STORE).delete('primary');
        tx.oncomplete = resolve;
        tx.onerror = resolve;
      });
    }
  }

  function toBoardUpper(str) {
    return String(str == null ? '' : str).toLocaleUpperCase('pl-PL');
  }

  function stripDiacritics(str) {
    const map = {
      'Ą': 'A', 'Ć': 'C', 'Ę': 'E', 'Ł': 'L', 'Ń': 'N', 'Ó': 'O', 'Ś': 'S', 'Ź': 'Z', 'Ż': 'Z',
      'ą': 'a', 'ć': 'c', 'ę': 'e', 'ł': 'l', 'ń': 'n', 'ó': 'o', 'ś': 's', 'ź': 'z', 'ż': 'z'
    };
    return String(str == null ? '' : str)
      .replace(/[ĄĆĘŁŃÓŚŹŻąćęłńóśźż]/g, function (ch) { return map[ch] || ch; })
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '');
  }

  function getCharAdvance(variant) {
    if (variant === 'condensed') {
      return { width: 4, spacing: 1, height: 9 };
    }
    return { width: 5, spacing: 1, height: 9 };
  }

  function getGlyph(ch, variant) {
    const upper = toBoardUpper(ch);
    if (variant === 'condensed') {
      return CONDENSED[upper] || CONDENSED[stripDiacritics(upper)] || CONDENSED[' '];
    }
    return STANDARD[upper] || STANDARD[stripDiacritics(upper)] || STANDARD[' '];
  }

  function measureText(str, variant) {
    const text = String(str == null ? '' : str);
    if (!text.length) return 0;
    const adv = getCharAdvance(variant);
    return text.length * adv.width + (text.length - 1) * adv.spacing;
  }

